'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const c=require('../sentlog/damage-catalog.js');
assert.equal(c.entries.length,83);
assert.equal(c.entries.filter(e=>!e.legacy).length,82);
assert.equal(new Set(c.entries.map(e=>e.name)).size,c.entries.length);
assert.equal(new Set(c.entries.map(e=>e.id)).size,c.entries.length);
for(const e of c.entries){assert.ok(c.materials[e.group]);assert.ok(Array.isArray(e.aliases));for(const r of e.refs){assert.ok(c.sources[r.source]);assert.ok(r.item)}}
const allBridge=c.entries.flatMap(e=>e.refs.filter(r=>r.source==='bridge').map(r=>Number(r.item.slice(0,2))));
for(let i=1;i<=26;i++)assert.ok(allBridge.includes(i),'Missing bridge reference '+i);
const shizuoka=c.entries.flatMap(e=>e.refs.filter(r=>r.source==='shizuoka').map(r=>r.item));
for(let i=1;i<=26;i++)assert.equal(shizuoka.filter(s=>Number(s.slice(0,2))===i).length,1);
assert.ok(shizuoka.includes('10 コンクリート補強材の損傷'));
assert.ok(shizuoka.includes('16 支承の機能障害'));
assert.ok(!shizuoka.includes('10 補修・補強材の損傷'));
assert.equal(c.matchName(c.entries,'ひびわれ').name,'ひび割れ');
assert.equal(c.matchName(c.entries,'うき').name,'浮き');
assert.equal(c.matchName(c.entries,'発錆').name,'腐食');
assert.equal(c.matchName(c.entries,'  腐食  ').name,'腐食');
assert.ok(c.filter(c.entries,'concrete','ポップ').some(e=>e.name==='ポップアウト'));
assert.ok(c.filter(c.entries,'concrete','漏水').some(e=>e.name==='漏水'));
assert.ok(c.filter(c.entries,'steel','漏水').some(e=>e.name==='漏水'));
assert.ok(!c.filter(c.entries,'steel').some(e=>e.name==='ポップアウト'));
assert.ok(c.filter(c.entries,'all','支承の機能').some(e=>e.name==='支承部の機能障害'));
for(const s of ['','   ','x'.repeat(41),'a\nb','__proto__','constructor'])assert.throws(()=>c.validName(s));
assert.equal(c.validName(' 補修材の再剥離 '),'補修材の再剥離');
assert.equal(c.validName('あ'.repeat(40)).length,40);
const p={id:'p1',damageNamesV1:[{id:'custom-1',name:'補修材の再剥離',material:'concrete'}]};
const shapes=[{type:'ひびわれ',typeNo:7,id:'old-a'},{type:'客先指定名称',id:'old-b'}];
const before=JSON.stringify({p,shapes}),list=c.forProject(p,shapes);
assert.equal(JSON.stringify({p,shapes}),before,'Catalog must not migrate saved shapes');
assert.ok(list.find(e=>e.name==='ひびわれ').legacy);
assert.ok(list.find(e=>e.name==='客先指定名称').legacy);
assert.ok(list.find(e=>e.name==='補修材の再剥離').custom);
assert.ok(!c.forProject({id:'another'},[]).some(e=>e.name==='補修材の再剥離'));
assert.ok(!c.entries.some(e=>['ASR','中性化','塩害','圧縮強度','中性化深さ'].includes(e.name)));
const src=fs.readFileSync(require.resolve('../sentlog/damage-catalog.js'),'utf8');
assert.ok(!/\bfetch\s*\(/.test(src),'Catalog must be usable offline');
assert.ok(!/innerHTML\s*=/.test(src),'Names must be rendered as text, not HTML');
console.log('PASS: 82 referenced/derived names + 1 legacy, both bridge editions, aliases, material/common filters, validation, project isolation, no migration');
