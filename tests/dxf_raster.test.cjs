'use strict';
const assert=require('node:assert/strict');
const core=require('../sentlog/dxf-raster-core.js');
function dxf({paper=false,clip=true}={}){
 const groups=[];
 const pair=(code,v)=>{groups.push(String(code),String(v));};
 const rec=(name,fields)=>{pair(0,name);for(const [code,v] of fields)pair(code,v);};
 rec('SECTION',[[2,'HEADER']]);
 pair(9,'$ACADVER');pair(1,'AC1032');pair(9,'$INSUNITS');pair(70,4);
 rec('ENDSEC',[]);
 rec('SECTION',[[2,'OBJECTS']]);
 rec('IMAGEDEF',[[5,'A1'],[100,'AcDbRasterImageDef'],[1,'C:\\plans\\field-photo.tif'],[10,10],[20,20]]);
 rec('ENDSEC',[]);
 rec('SECTION',[[2,'ENTITIES']]);
 rec('IMAGE',[[5,'B1'],[100,'AcDbRasterImage'],[340,'A1'],[10,100],[20,200],[11,2],[21,0],[12,0],[22,3],[13,10],[23,20],[70,1],...(paper?[[67,1]]:[]),...(clip?[[280,1],[71,2],[14,0],[24,0],[14,10],[24,0],[14,10],[24,20]]:[])] );
 rec('ENDSEC',[]);rec('EOF',[]);
 return new TextEncoder().encode(groups.join('\r\n')+'\r\n');
}
const decoded=core.parse(dxf());
assert.deepEqual(decoded.references.map(x=>[x.handle,x.fileName]),[['A1','field-photo.tif']]);
assert.equal(decoded.placements.length,1);
const item=decoded.placements[0];
assert.equal(item.clip.length,3);
assert.deepEqual(item.clip.map(x=>[x.x,x.y]),[[0,0],[10,0],[10,20]]);
assert.equal(item.visible,true);
const frame={xMin:50,yMax:400,unitsPerPixel:1};
const view={scale:2,tx:10,ty:20};
assert.deepEqual(core.imageTransform(item,frame,view,10,20),{a:4,b:0,c:0,d:6,e:110,f:300});
const scaled=core.imageTransform(item,frame,view,20,40);
assert.deepEqual([scaled.a,scaled.d,scaled.e,scaled.f],[2,3,110,300],'image resolution must not change world size');
const union=core.includeBounds({minX:0,minY:0,maxX:1,maxY:1},decoded);
assert.deepEqual(union,{minX:0,minY:0,maxX:120,maxY:260});
assert.equal(core.parse(dxf({paper:true})).placements.length,0,'paper image should not leak into model space');
const unclipped=core.parse(dxf({clip:false}));
assert.equal(unclipped.placements[0].clipEnabled,false);
assert.equal(core.basename('D:\\archive\\subdir\\Image.TIFF'),'Image.TIFF');
assert.throws(()=>core.imageTransform(item,{unitsPerPixel:0},view,10,20),/座標系/);
console.log('PASS CAD TIF references: IMAGEDEF, raster geometry, clip, model/paper separation and filenames');
