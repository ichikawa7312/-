import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const license = await readFile(resolve(here, 'node_modules/@noble/hashes/LICENSE'), 'utf8');
await writeFile(resolve(here, 'noble-hashes-LICENSE.txt'), license);
await build({
  absWorkingDir: here,
  entryPoints: ['runtime.js'],
  outfile: resolve(here, '../../sentlog/blob-sha256.js'),
  bundle: true,
  platform: 'browser',
  format: 'iife',
  globalName: 'SentlogBlobSha256Build',
  target: ['es2020'],
  treeShaking: true,
  minify: false,
  legalComments: 'inline',
  banner: { js: '/* Generated by tools/blob-hash-runtime/build.mjs. @noble/hashes 2.0.1 (MIT).\n * Rebuild with npm ci && npm run build in that directory. No network runtime dependency. */' },
  footer: { js: "if(typeof module==='object'&&module.exports)module.exports=Object.freeze(SentlogBlobSha256Build);else (typeof window!=='undefined'?window:globalThis).SentlogBlobSha256=Object.freeze(SentlogBlobSha256Build);" }
});
